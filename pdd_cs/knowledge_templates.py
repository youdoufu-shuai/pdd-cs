AFTER_SALES_PLAYBOOK = """# 售后处理手册（请按店铺真实政策填写）

> 原则：智能客服负责「接住情绪、收集信息、按平台规则解释、马上转人工」；
> 是否退款/退货/赔偿、赔多少，由人工按平台规则和店铺政策决定。
> 客服在对话里不承诺结果、不承诺时间、不承诺金额，也不引导客户站外处理。

## 一、通用处理流程（每一步都要做）

1. **先安抚**：客户着急时先说一句「您别着急，我帮您处理」。
2. **收集信息**：订单号后四位、商品名称、具体问题、照片/视频；只问最关键的一个。
3. **说明流程**：按平台页面流程解释（售后申请 → 寄回 → 商家验收 → 平台退款），不承诺结果。
4. **马上转人工**：售后协商、退款、退货、赔偿、投诉、安全类问题，立即转人工跟进。
5. **人工接手**：人工核实订单和凭证后，再给出处理方案。

## 二、分类处理口径

### 1. 退款 / 退货 / 换货 / 仅退款 / 赔付 / 补偿

- 可以讲：平台售后入口、需要客户怎么操作、大概流程。
- 不能讲：「肯定能退」「包退」「我帮你申请仅退款」「赔你多少钱」「今天到账」。
- 必须收集：订单号后四位、商品名、问题描述、照片或视频。
- 处理：说明「售后以平台页面处理结果为准」，立即转人工。

### 2. 质量问题 / 破损 / 少发 / 错发 / 漏发 / 假货

- 可以讲：需要客户提供实物照片、外包装照片、快递面单。
- 不能讲：直接承认责任、承诺补发时间、承诺赔偿金额。
- 处理：收集凭证后转人工核实仓库/快递。

### 3. 物流异常 / 迟迟不更新 / 未收到

- 可以讲：物流以订单页为准，帮客户核对；已发货的改地址需要人工拦截。
- 不能讲：「已经发了」「明天到」「保证拦截成功」。
- 处理：查订单页仍无更新 → 转人工联系快递。

### 4. 发票 / 改地址 / 订单备注

- 发票：收集订单号、抬头、税号、邮箱，转人工开票。
- 发货前改地址：引导客户在订单页自行修改；已发货：转人工尝试拦截。
- 订单备注：不承诺一定备注成功，特殊需求转人工。

### 5. 投诉 / 差评 / 监管 / 人身安全

- 投诉/差评/12315/媒体：先安抚，不辩解，立即转人工/负责人。
- 过敏、受伤、异物、食品安全、漏电、起火：立即转人工并停止自动回复，保留证据。
- 绝不评价平台、不评价同行、不使用「最/第一/100%/保证」等绝对化表述。

## 三、标准话术（可直接复制修改）

- 安抚：您别着急，我帮您看一下，马上为您处理。
- 收集：麻烦发我订单号后四位和问题照片，我帮您转售后客服核实。
- 流程：售后处理以平台页面显示为准，我帮您转人工客服跟进，请稍等～
- 退款：退款到账时间以平台页面显示为准，我帮您转人工确认进度。
- 质量：麻烦拍一下商品和包装的照片，我帮您转售后人工核实处理。
- 转人工：已经为您转接人工客服，请稍等片刻，人工会继续为您处理。

## 四、转人工后的交接清单

- 客户诉求（退款 / 换货 / 赔偿 / 咨询）
- 订单号后四位
- 问题描述与照片/视频
- 客户情绪状态
- 已说过的口径与未承诺事项
"""

TEMPLATES = {
    "product-catalog.md": PRODUCT_CATALOG,
    "after-sales-playbook.md": AFTER_SALES_PLAYBOOK,
}


def ensure_knowledge_templates(config: Config) -> dict[str, list[str]]:
    """按需生成商品/售后模板；已存在的文件不覆盖。"""
    directory: Path = config.knowledge.dir
    directory.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    skipped: list[str] = []
    for name, text in TEMPLATES.items():
        path = directory / name
        if path.exists():
            skipped.append(name)
            continue
        path.write_text(text, encoding="utf-8")
        created.append(name)
    return {"created": created, "skipped": skipped}


